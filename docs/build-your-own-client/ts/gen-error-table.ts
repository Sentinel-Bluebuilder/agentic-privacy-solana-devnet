// ─── Print the BUILD-YOUR-OWN-CLIENT.md §9 error table from errors.ts + the IDL ───
// Usage: npx tsx gen-error-table.ts > table.md   (or --check <doc> to fail when the doc drifted)
import fs from 'node:fs';
import { allRows } from './errors.ts';

const START = '<!-- error-table:start (generated by ts/gen-error-table.ts) -->';
const END = '<!-- error-table:end -->';
const cell = (s: string) => s.replace(/\|/g, '\\|');
const lines = [
  '| number | name | meaning | money moved? | fix |',
  '|---|---|---|---|---|',
  ...allRows().map((r) => `| ${r.code} | \`${r.name}\` | ${cell(r.meaning)} | ${cell(r.moneyMoved)} | ${cell(r.fix)} |`),
];
const table = `${START}\n${lines.join('\n')}\n${END}`;

const i = process.argv.indexOf('--check');
if (i >= 0) {
  const doc = fs.readFileSync(process.argv[i + 1], 'utf8');
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  const inDoc = a >= 0 && b > a ? doc.slice(a, b + END.length) : '';
  if (inDoc !== table) {
    console.error('error table in the doc differs from errors.ts: regenerate it');
    process.exit(1);
  }
  console.log(`error table matches (${lines.length - 2} rows)`);
} else {
  console.log(table);
}
